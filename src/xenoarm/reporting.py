"""Portable HTML/video report with local plots and no external web dependencies."""

import html
import json
import os
from pathlib import Path

import numpy as np


def _plot_episode(result, output):
    os.environ.setdefault("MPLCONFIGDIR", str(output / ".cache/matplotlib"))
    from matplotlib.backends.backend_agg import FigureCanvasAgg
    from matplotlib.figure import Figure

    trace = result["trace"]
    steps = [r["step"] for r in trace]
    figure = Figure(figsize=(10, 4.8), layout="constrained")
    FigureCanvasAgg(figure)
    provenance, latency = figure.subplots(2, 1, sharex=True)
    provenance.step(
        steps,
        [r["command_version"] for r in trace],
        where="post",
        label="Current instruction",
        color="#2563eb",
        linewidth=2,
    )
    provenance.step(
        steps,
        [r["action_version"] for r in trace],
        where="post",
        label="Executed chunk",
        color="#f97316",
        linestyle="--",
    )
    for row in trace:
        if row["stale"]:
            provenance.axvspan(row["step"] - 0.5, row["step"] + 0.5, alpha=0.12, color="#f97316")
    for event in result["corrections"]:
        for axis in (provenance, latency):
            axis.axvline(event["step"], color="#64748b", linestyle=":")
    provenance.set(
        ylabel="Command version",
        title=f"Seed {result['seed']} · {result['mode']} · success={result['success']}",
    )
    provenance.legend(loc="upper left")
    latency.plot(
        steps, [r["control_ms"] for r in trace], label="Control / dispatch", color="#2563eb"
    )
    inference_rows = [r for r in trace if r["inference_ms"] is not None]
    latency.scatter(
        [r["step"] for r in inference_rows],
        [r["inference_ms"] for r in inference_rows],
        label="Chunk inference",
        color="#16a34a",
        s=20,
    )
    latency.set(xlabel="Control step (not wall-clock video time)", ylabel="Milliseconds")
    latency.legend(loc="upper left")
    for axis in (provenance, latency):
        axis.grid(alpha=0.2)
    directory = output / "plots"
    directory.mkdir(exist_ok=True)
    path = directory / f"seed-{result['seed']}.png"
    figure.savefig(path, dpi=120)
    return path.relative_to(output).as_posix()


def _format(value, *, percent=False):
    if value is None:
        return "Not measured"
    if isinstance(value, bool):
        return "Yes" if value else "No"
    return f"{value * 100:.1f}%" if percent else f"{value:.2f}"


def generate_report(directory, metadata=None):
    output = Path(directory).resolve()
    if metadata is None:
        metadata = json.loads((output / "metadata.json").read_text())
    source = output / "episodes.jsonl"
    rows = [json.loads(line) for line in source.read_text().splitlines() if line.strip()]
    summary = {
        "status": metadata["status"],
        "episodes": len(rows),
        "success_rate": float(np.mean([r["success"] for r in rows])) if rows else None,
    }
    for field in ("correction_success", "stale_action_rate", "inference_p95_ms", "control_p95_ms"):
        values = [r[field] for r in rows if r.get(field) is not None]
        summary[f"mean_episode_{field}"] = float(np.mean(values)) if values else None
    (output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    cards = []
    for result in rows:
        plot = _plot_episode(result, output)
        media = result.get("video")
        if media:
            # Media paths are generated by the recorder, not copied from arbitrary text.
            video = f'<video controls preload="metadata" poster="{html.escape(media["poster"], quote=True)}"><source src="{html.escape(media["path"], quote=True)}" type="video/mp4"></video>'
        else:
            video = '<p class="hint">No recording for this episode. Run with <code>--video</code> to record simulator cameras.</p>'
        events = html.escape(json.dumps(result["corrections"], indent=2, ensure_ascii=False))
        cards.append(f'''<article id="seed-{result["seed"]}">
<h2>Seed {result["seed"]} <span class="badge">{"SUCCESS" if result["success"] else "FAILED"}</span></h2>
<p>Steps: {result["steps"]} · Correction success: {_format(result["correction_success"])} · Stale action rate: {_format(result["stale_action_rate"], percent=True)}</p>
{video}<img src="{plot}" alt="Instruction provenance and inference latency plot for seed {result["seed"]}" loading="lazy">
<details><summary>Correction events</summary><pre>{events}</pre></details></article>''')
    name = html.escape(metadata["config"]["name"])
    status = html.escape(metadata["status"])
    backend = html.escape(metadata["config"]["environment"]["backend"])
    navigation = " ".join(f'<a href="#seed-{r["seed"]}">Seed {r["seed"]}</a>' for r in rows)
    document = f"""<!doctype html><html lang="en"><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1"><title>{name} — XenoArm</title>
<style>
body{{font:16px/1.6 system-ui,sans-serif;margin:0;background:#f1f5f9;color:#0f172a}}
main{{max-width:1080px;margin:auto;padding:28px}} h1{{line-height:1.2}} .meta,.hint{{color:#475569}}
article,.overview{{background:white;border:1px solid #e2e8f0;border-radius:16px;padding:24px;margin:24px 0}}
video,img{{display:block;width:100%;border-radius:8px}} video{{background:#0f172a;max-height:640px}}
.badge{{font-size:12px;letter-spacing:.06em;background:#e2e8f0;padding:6px 10px;border-radius:20px}}
nav a{{display:inline-block;padding:6px 12px;margin:4px;border-radius:8px;background:#dbeafe;color:#1d4ed8;text-decoration:none}}
pre{{white-space:pre-wrap;overflow-wrap:anywhere;background:#f8fafc;padding:12px;border-radius:8px}} code{{font-family:monospace}}
</style><main><h1>{name}</h1><p class="meta">XenoArm · {backend} · Status: {status}</p>
<section class="overview"><b>{len(rows)} completed episodes</b> · Success: {_format(summary["success_rate"], percent=True)}
<p>Correction success: {_format(summary["mean_episode_correction_success"], percent=True)} · Mean episode stale action rate: {_format(summary["mean_episode_stale_action_rate"], percent=True)}</p>
<p>Mean episode inference P95: {_format(summary["mean_episode_inference_p95_ms"])} ms · Mean episode control P95: {_format(summary["mean_episode_control_p95_ms"])} ms</p>
<p class="hint">Dashed vertical lines mark corrections. Orange shading marks old-command actions. Video uses sampled control steps at fixed playback FPS; it does not show real-time model speed. Recording/tracking overhead is excluded from control/inference timers, but included in episode wall time. Uninstrumented physical safety fields remain null.</p>
<nav>{navigation}</nav></section>{"".join(cards)}</main></html>"""
    path = output / "report.html"
    path.write_text(document, encoding="utf-8")
    return path
